Project 01 – Database Creation
Overview

This project demonstrates the fundamental process of creating a relational database and a table using SQL. It serves as an introduction to SQL Data Definition Language (DDL) by creating a database, defining a table structure with appropriate data types, and inserting sample records.

Understanding database creation is one of the first skills required for data analysts, database developers, and data engineers because every data-driven application relies on a well-structured database.

Project Objectives

The objectives of this project are to:

Create a new database named PEOPLE
Create a table named TBLpeople
Define appropriate data types for each column
Insert sample records into the table
Demonstrate different methods of inserting data
